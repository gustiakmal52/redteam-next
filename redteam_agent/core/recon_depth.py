"""Passive recon depth: WAF fingerprinting, TLS certificate inspection, and
optional naabu port scanning. Everything here is read-only reconnaissance;
no vulnerability findings are fabricated, only observed markers are recorded.
"""

from __future__ import annotations

import asyncio
import datetime
import os
import re
import socket
import ssl
import urllib.parse
from typing import Any, Dict, List, Optional

from redteam_agent.core.config import TOOL_PATHS
from redteam_agent.core.task_manager import ScanTask
from redteam_agent.core.http_verifier import HTTPVerifier
from redteam_agent.core.bypass_engine import ProtectionFingerprintEngine


WAF_SIGNATURES = {
    "Cloudflare": {
        "cookies": ["__cfduid", "__cf_bm", "cf_clearance"],
        "headers": ["cf-ray", "server:cloudflare"],
        "body": ["Attention Required! | Cloudflare", "cf-error-details"],
    },
    "AWS WAF / CloudFront": {
        "headers": ["x-amz-cf-id", "x-amzn-requestid", "server:cloudfront"],
        "body": ["Generated by cloudfront", "Request blocked"],
    },
    "Akamai Ghost": {
        "headers": ["x-akamai-transformed", "server:akamaighost"],
        "body": ["This website is using a security service to protect itself from online attacks."],
    },
    "Imperva / Incapsula": {
        "cookies": ["incap_ses_", "visid_incap_"],
        "headers": ["x-iinfo"],
        "body": ["Incapsula incident ID"],
    },
    "F5 BIG-IP ASM": {
        "cookies": ["TS[0-9a-f]{4,8}"],
        "headers": ["x-cnection", "server:bigip"],
    },
    "Sucuri": {
        "headers": ["x-sucuri-id", "x-sucuri-cache"],
        "body": ["Sucuri WebSite Firewall"],
    },
    "Wordfence": {
        "body": ["503 Service Unavailable", "wordfence"],
    },
    "Barracuda WAF": {
        "headers": ["x-wa-info", "server:barracuda"],
        "cookies": ["barra_counter_session"],
    },
    "Citrix NetScaler": {
        "headers": ["ns_af"],
        "cookies": ["citrix_ns_id", "NSC_"],
    },
}


class ReconDepth:
    """Runs passive WAF/TLS/port reconnaissance with the shared traffic controls."""

    def __init__(self, task: ScanTask, verifier: HTTPVerifier):
        self.task = task
        self.verifier = verifier
        self.scope = task.scope_manager

    async def run_all(self, base_url: str) -> Dict[str, Any]:
        await self.task.emit_log("INFO", "[DEPTH] WAF fingerprint, TLS inspection, optional port scan",
                                 "Recon Depth", 66)
        results: Dict[str, Any] = {"waf": None, "tls": None, "ports": [], "notes": []}
        parsed = urllib.parse.urlparse(base_url)
        host = parsed.hostname or ""
        if self.scope.check_url(base_url, active=True).get("allowed"):
            results["waf"] = await asyncio.to_thread(self.detect_waf, base_url)
        if parsed.scheme == "https" and host:
            results["tls"] = await asyncio.to_thread(self.inspect_tls, host)
        if host:
            results["ports"] = await self.run_port_scan(host)
        waf_name = (results["waf"] or {}).get("detected") or "none-observed"
        tls_note = "none-observed" if not results["tls"] else (results["tls"].get("note") or "certificate-observed")
        await self.task.emit_log("SUCCESS",
            f"[DEPTH] WAF={waf_name} TLS={tls_note} open_ports={len(results['ports'])}", progress=70)
        return results

    def detect_waf(self, url: str) -> Dict[str, Any]:
        """Sends a normal request and a tamper request, then matches observed
        headers/cookies/body markers against known WAF signatures."""
        normal = self.verifier.send_http_request(url, priority="normal")
        tamper_url = url + ("&" if "?" in url else "?") + "x=../../../../etc/passwd%00"
        tamper = self.verifier.send_http_request(tamper_url, priority="normal")
        responses = [r for r in (normal, tamper) if r.get("status_code")]
        detected: List[str] = []
        evidence: Dict[str, Any] = {"headers": {}, "cookies": [], "blocked_status": None}
        for resp in responses:
            headers = {str(k).lower(): str(v) for k, v in resp.get("headers", {}).items()}
            body = resp.get("body", "")
            for name, sig in WAF_SIGNATURES.items():
                if name in detected:
                    continue
                for marker in sig.get("headers", []):
                    key, _, value = marker.partition(":")
                    if key in headers and (not value or value.strip().lower() in headers[key].lower()):
                        detected.append(name)
                        evidence["headers"][name] = marker
                        break
                if name in detected:
                    continue
                for cookie in sig.get("cookies", []):
                    if any(re.search(rf"(^|[\s;]){cookie}", c, re.I) for c in headers.get("set-cookie", "").split(";")):
                        detected.append(name)
                        evidence["cookies"].append(f"{name}:{cookie}")
                        break
                if name in detected:
                    continue
                for body_marker in sig.get("body", []):
                    if body_marker.lower() in body.lower():
                        detected.append(name)
                        break
        if tamper.get("status_code") and normal.get("status_code") and \
                tamper["status_code"] in (403, 406, 429, 503) and tamper["status_code"] != normal["status_code"]:
            evidence["blocked_status"] = tamper["status_code"]
        # Feed the exact observed responses into the adaptive fingerprint
        # implementation as well. The legacy fields remain for dashboard/API
        # compatibility; no vendor is inferred from a single header.
        adaptive = ProtectionFingerprintEngine().fingerprint(responses)
        return {
            "detected": adaptive.get("detected") or detected,
            "confidence": adaptive.get("confidence", 0.0),
            "fingerprints": adaptive.get("fingerprints", []),
            "response_features": adaptive.get("responses", []),
            "evidence": {**evidence, "adaptive": adaptive},
            "observed": bool(detected) or bool(evidence["blocked_status"]) or adaptive.get("observed", False),
        }

    def inspect_tls(self, host: str, port: int = 443) -> Optional[Dict[str, Any]]:
        """Grabs the TLS certificate and reports SAN/expiry observation."""
        try:
            context = ssl.create_default_context()
            with socket.create_connection((host, port), timeout=self.verifier.timeout) as sock:
                with context.wrap_socket(sock, server_hostname=host) as tls:
                    der = tls.getpeercert(binary_form=False)
                    if not der:
                        return {"host": host, "note": "certificate-available-but-unparsed", "observed": True}
                    not_after = der.get("notAfter", "")
                    san = []
                    for entry in der.get("subjectAltName", []):
                        if entry[0] == "DNS":
                            san.append(entry[1])
                    days_left = None
                    if not_after:
                        try:
                            expiry = datetime.datetime.strptime(not_after, "%b %d %H:%M:%S %Y %Z")
                            days_left = (expiry - datetime.datetime.utcnow()).days
                        except ValueError:
                            pass
                    return {
                        "host": host, "subject": der.get("subject"), "issuer": der.get("issuer"),
                        "not_after": not_after, "days_left": days_left, "san": sorted(set(san)),
                        "expiring_soon": days_left is not None and days_left < 14,
                        "observed": True,
                    }
        except Exception as exc:
            return {"host": host, "note": f"tls_inspection_failed: {exc}", "observed": False}

    async def _run_async_command(self, cmd: List[str], tool_label: str) -> List[str]:
        output_lines: List[str] = []
        proc = None
        try:
            await self.task.emit_log("INFO", f"[{tool_label}] Executing: {' '.join(cmd)}")
            proc = await asyncio.create_subprocess_exec(
                *cmd, stdout=asyncio.subprocess.PIPE, stderr=asyncio.subprocess.PIPE)
            self.task.register_process(proc)
            while True:
                line = await proc.stdout.readline()
                if not line:
                    break
                decoded = line.decode("utf-8", errors="ignore").strip()
                if decoded:
                    output_lines.append(decoded)
            return_code = await proc.wait()
            stderr = (await proc.stderr.read()).decode("utf-8", errors="replace").strip()
            self.task.results["tool_runs"].append({"tool": tool_label, "status": "failed" if return_code else
                ("success" if output_lines else "no_output"), "return_code": return_code,
                "reason": stderr[:500] if return_code else ("completed" if output_lines else "no open ports found"),
                "output_count": len(output_lines), "verified": return_code == 0 and bool(output_lines)})
        except Exception as e:
            self.task.results["tool_runs"].append({"tool": tool_label, "status": "failed",
                "reason": str(e), "verified": False})
        finally:
            if proc is not None:
                self.task.unregister_process(proc)
        return output_lines

    async def run_port_scan(self, host: str) -> List[Dict[str, Any]]:
        """Optional naabu TCP port scan; records only observed open ports."""
        binary = TOOL_PATHS.get("naabu")
        if not binary or not os.path.exists(binary):
            self.task.results["tool_runs"].append({"tool": "naabu", "status": "failed",
                "reason": "tool missing", "verified": False})
            return []
        try:
            rps = int(self.verifier.traffic.config.get("per_host_rps", 3))
            lines = await self._run_async_command(
                [binary, "-host", host, "-top-ports", "200", "-silent",
                 "-rate", str(rps), "-c", "10", "-timeout", "3000"], "naabu")
        except Exception as exc:
            self.task.results["tool_runs"].append({"tool": "naabu", "status": "failed",
                "reason": str(exc), "verified": False})
            return []
        ports: List[Dict[str, Any]] = []
        seen = set()
        for line in lines:
            try:
                port = int(line.split(":")[-1].split("/")[0])
            except (ValueError, IndexError):
                continue
            if port and port not in seen:
                seen.add(port)
                ports.append({"host": host, "port": port, "state": "open", "source": "naabu", "observed": True})
        return ports
